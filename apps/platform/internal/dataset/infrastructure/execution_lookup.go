package infrastructure

import (
	"context"
	"errors"
	"fmt"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/qq550723504/data-product-platform/apps/platform/internal/dataset/domain"
)

func (r *PostgresRepository) FindVersionByExecution(ctx context.Context, executionID uuid.UUID) (domain.DatasetVersion, error) {
	version, err := scanVersion(r.pool.QueryRow(ctx, `
		SELECT `+versionColumns+`
		FROM dataset_version
		WHERE generated_by_execution_id = $1
		ORDER BY version_no DESC
		LIMIT 1
	`, executionID))
	if errors.Is(err, ErrNotFound) || errors.Is(err, pgx.ErrNoRows) {
		return domain.DatasetVersion{}, ErrNotFound
	}
	if err != nil {
		return domain.DatasetVersion{}, fmt.Errorf("find DatasetVersion generated by execution %s: %w", executionID, err)
	}
	return version, nil
}
