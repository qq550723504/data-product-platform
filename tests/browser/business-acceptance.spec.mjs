 await page.getByRole('button',{name:'确认冻结并提交验收'}).click();
 await page.getByRole('combobox',{name:'演示办理身份',exact:true}).selectOption('reviewer');
 await page.getByRole('combobox',{name:'核验 统计期间符合需求',exact:true}).selectOption('FAIL');
 await page.getByRole('textbox',{name:'办理说明',exact:true}).fill('补充统计期间核对说明');
 await page.getByRole('button',{name:'退回修改',exact:true}).click();
 await expect(page.getByText(/DEMO-DEC-.*已退回/)).toBeVisible();
 await page.getByRole('combobox',{name:'演示办理身份',exact:true}).selectOption('provider');
 await page.getByRole('button',{name:'确认冻结并提交验收'}).click();
 await page.getByRole('combobox',{name:'演示办理身份',exact:true}).selectOption('reviewer');
 for(const name of ['字段与约定一致','统计期间符合需求','成果满足业务使用要求'])await page.getByRole('combobox',{name:'核验 '+name,exact:true}).selectOption('PASS');
 await page.getByRole('textbox',{name:'办理说明',exact:true}).fill('逐项核对满足业务要求');
 await page.getByRole('button',{name:'确认验收通过',exact:true}).click();
