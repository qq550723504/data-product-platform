 await page.getByRole('textbox',{name:'签收依据',exact:true}).fill('DEMO-EVIDENCE-COMPLETE');
 await page.getByRole('textbox',{name:'签收说明',exact:true}).fill('逐项确认演示成果完整收到');
 await page.getByRole('button',{name:'保存签收记录',exact:true}).click();
 await page.getByRole('button',{name:'进入业务验收',exact:true}).click();
